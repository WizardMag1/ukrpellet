/**
 * UkrEcoPelleta & ТОВ «УКРЕКОПЕЛЕТА» — Main Application Scripts
 * Mobile navigation, modal dialogues, toast feedback, form submission, ad tracking
 */

document.addEventListener('DOMContentLoaded', () => {
  // 1. Mobile Menu Toggle
  const mobileToggle = document.getElementById('mobile-menu-toggle');
  const navMenu = document.getElementById('nav-menu');

  if (mobileToggle && navMenu) {
    mobileToggle.addEventListener('click', () => {
      const isExpanded = mobileToggle.getAttribute('aria-expanded') === 'true';
      mobileToggle.setAttribute('aria-expanded', !isExpanded);
      navMenu.classList.toggle('open');
    });

    // Close mobile menu on nav link click
    navMenu.querySelectorAll('.nav-link').forEach(link => {
      link.addEventListener('click', () => {
        navMenu.classList.remove('open');
        mobileToggle.setAttribute('aria-expanded', 'false');
      });
    });
  }

  // 2. Header shadow on scroll
  const header = document.querySelector('.site-header');
  window.addEventListener('scroll', () => {
    if (window.scrollY > 20) {
      header?.classList.add('scrolled');
    } else {
      header?.classList.remove('scrolled');
    }
  }, { passive: true });

  // 3. Modal Dialog Controller
  const contactModal = document.getElementById('contact-dialog');
  const openModalBtns = document.querySelectorAll('[data-open-modal], .js-open-modal');
  const closeModalBtns = document.querySelectorAll('[data-close-modal]');

  openModalBtns.forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      if (contactModal && typeof contactModal.showModal === 'function') {
        contactModal.showModal();
      }
    });
  });

  closeModalBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      if (contactModal) {
        contactModal.close();
      }
    });
  });

  // Close modal when clicking outside on the backdrop
  if (contactModal) {
    contactModal.addEventListener('click', (e) => {
      const rect = contactModal.getBoundingClientRect();
      const isInDialog = (
        rect.top <= e.clientY &&
        e.clientY <= rect.top + rect.height &&
        rect.left <= e.clientX &&
        e.clientX <= rect.left + rect.width
      );
      if (!isInDialog) {
        contactModal.close();
      }
    });
  }

  // 4. Form Handling with API Integration & Ad Tracking
  const leadForms = document.querySelectorAll('.quote-lead-form');
  const toastMsg = document.getElementById('toast-notification');

  function showToast(message) {
    if (!toastMsg) return;
    const textSpan = toastMsg.querySelector('.toast-text');
    if (textSpan) textSpan.textContent = message;
    toastMsg.classList.add('show');
    setTimeout(() => {
      toastMsg.classList.remove('show');
    }, 5000);
  }

  // ---- Quote form logistics (block generated by scripts/sync-layout.cjs) ----------------------------
  // Shows the pickup or delivery questions, warns about combinations that won't work, makes email
  // required when the buyer asks for our equipment (we confirm that by email), and writes a summary.
  const siteLang = () => { try { return localStorage.getItem('site_lang') || 'uk'; } catch (e) { return 'uk'; } };
  const WARN = {
    capacity: (c, t, trips) => [
      `Вантажопідйомність ${c} т менша за замовлення ${t} т: потрібно ${trips} ${trips % 10 >= 2 && trips % 10 <= 4 && (trips % 100 < 12 || trips % 100 > 14) ? 'рейси' : 'рейсів'} або більший транспорт.`,
      `Capacity ${c} t is less than the ${t} t order: ${trips} trips or a bigger vehicle.`],
    trailer: () => ['У легковий причіп вміщується 1 біг-бег (650 кг).', 'A car trailer takes 1 big bag (650 kg).'],
    rear: () => [
      'Через задні двері навантажувач ставить біг-беги лише біля дверей, тож поміститься менше. Краще транспорт із бічним або верхнім завантаженням.',
      'Through rear doors a forklift can only place bags near the door, so less fits. A side- or top-loading vehicle is better.'],
    topNoCrane: () => ['Зверху вантажимо тільки краном: позначте кран у допомозі.', 'Top loading needs our crane: tick the crane.'],
    crane: () => ['Кран працює на виробництві: дату й час погодимо окремо.', 'The crane works in production: we will agree the date and time separately.'],
    access: () => ['Менша машина — за окремим розрахунком, менеджер запропонує варіант.', 'A smaller vehicle is priced separately; our manager will suggest an option.'],
    unload: () => ['Менеджер запропонує, як розвантажити біг-беги на місці.', 'Our manager will suggest how to unload the bags on site.'],
    email: () => ['Потрібна наша допомога: вкажіть email, підтвердимо умови й час листом.', 'You need our help: add your email and we will confirm terms and time by email.'],
  };

  const checked = (form, name) => [...form.querySelectorAll(`input[name="${name}"]:checked`)].map((i) => i.value);
  const inactive = (el) => !!el.closest('[data-receive][hidden]');

  function orderTons(form) {
    const fromCalc = parseFloat(form.dataset.tons);
    if (fromCalc > 0) return fromCalc;
    const m = (form.querySelector('input[name="volume"]')?.value || '').replace(',', '.').match(/\d+(?:\.\d+)?/);
    return m ? parseFloat(m[0]) : 0;
  }

  // Returns the warnings as [uk, en] pairs
  function syncLogistics(form) {
    if (!form.querySelector('.logistics')) return [];
    const receive = checked(form, 'receive')[0] || '';
    form.querySelectorAll('[data-receive]').forEach((el) => {
      const on = el.dataset.receive === receive;
      el.hidden = !on;
      if (el.tagName === 'FIELDSET') el.disabled = !on;
      else el.querySelectorAll('input, select, textarea').forEach((i) => { i.disabled = !on; });
    });

    // Checkbox groups need at least one answer
    form.querySelectorAll('fieldset[data-need-one]').forEach((fs) => {
      const boxes = fs.querySelectorAll('input[type="checkbox"]');
      const any = [...boxes].some((b) => b.checked);
      if (boxes[0]) boxes[0].setCustomValidity(fs.disabled || any ? '' : (siteLang() === 'en' ? 'Choose at least one option.' : 'Оберіть хоча б один варіант.'));
    });

    const warn = [];
    const pickup = receive === 'Самовивіз';
    const tons = orderTons(form);
    let needsEquipment = false;
    if (pickup) {
      const vehicle = checked(form, 'vehicle')[0] || '';
      const opening = checked(form, 'opening');
      const help = checked(form, 'help');
      const cap = parseFloat(form.querySelector('input[name="capacity"]')?.value);
      if (cap > 0 && tons > cap) warn.push(WARN.capacity(cap, tons, Math.ceil(tons / cap)));
      if (vehicle === 'Легковий причіп' && tons > 0.65) warn.push(WARN.trailer());
      if (vehicle.startsWith('Фургон') || (opening.length === 1 && opening[0] === 'Ззаду')) warn.push(WARN.rear());
      if (opening.length === 1 && opening[0].startsWith('Зверху') && !help.includes('Кран')) warn.push(WARN.topNoCrane());
      if (help.includes('Кран')) warn.push(WARN.crane());
      needsEquipment = help.some((h) => h !== 'Нічого, завантажимо самі');
    } else if (receive === 'Доставка') {
      if (checked(form, 'access')[0]?.startsWith('Ні')) warn.push(WARN.access());
      if (checked(form, 'unloading')[0]?.startsWith('Техніки немає')) { warn.push(WARN.unload()); needsEquipment = true; }
    }
    const email = form.querySelector('input[name="email"]');
    if (email) email.required = needsEquipment;
    if (needsEquipment) warn.push(WARN.email());

    const list = form.querySelector('[data-logistics-warn]');
    if (list) {
      const en = siteLang() === 'en';
      list.textContent = '';
      warn.forEach((w) => {
        const li = document.createElement('li');
        li.textContent = en ? w[1] : w[0];
        list.appendChild(li);
      });
      list.hidden = warn.length === 0;
    }
    return warn;
  }

  // "Label: answer" lines for the sales team, in Ukrainian
  function logisticsSummary(form, warn) {
    const lines = [];
    form.querySelectorAll('.logistics [data-label]').forEach((el) => {
      if (inactive(el)) return;
      const values = [...el.querySelectorAll('input, select')]
        .filter((i) => !i.disabled && ((i.type === 'radio' || i.type === 'checkbox') ? i.checked : i.value.trim()))
        .map((i) => (i.type === 'date' ? i.value.split('-').reverse().join('.') : i.value.trim()));
      if (values.length) lines.push(`${el.dataset.label}: ${values.join(', ')}`);
    });
    // The email prompt is for the buyer; the sales team sees the requested help in the lines above
    warn.filter((w) => w[0] !== WARN.email()[0]).forEach((w) => lines.push(`Увага: ${w[0]}`));
    return lines.join('\n');
  }

  leadForms.forEach(form => {
    const date = form.querySelector('input[name="date"]');
    if (date) {
      const d = new Date();
      date.min = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
    }
    form.addEventListener('change', (e) => {
      // "We'll load it ourselves" and "we need your equipment" exclude each other
      if (e.target.name === 'help' && e.target.checked) {
        form.querySelectorAll('input[name="help"]').forEach((b) => {
          if (b !== e.target && (b.hasAttribute('data-exclusive') || e.target.hasAttribute('data-exclusive'))) b.checked = false;
        });
      }
      syncLogistics(form);
    });
    form.addEventListener('input', (e) => {
      if (e.target.name === 'capacity' || e.target.name === 'volume') syncLogistics(form);
    });
    // form.reset() restores the default choice after the reset event, so re-sync on the next tick
    form.addEventListener('reset', () => setTimeout(() => { delete form.dataset.tons; syncLogistics(form); }, 0));
    window.addEventListener('languageChanged', () => syncLogistics(form));
    syncLogistics(form);

    form.addEventListener('submit', async (e) => {
      e.preventDefault();

      const nameInput = form.querySelector('input[name="name"]');
      const phoneInput = form.querySelector('input[name="phone"]');
      const emailInput = form.querySelector('input[name="email"]');
      const cityInput = form.querySelector('input[name="city"]');
      const volumeInput = form.querySelector('input[name="volume"]');
      const commentInput = form.querySelector('textarea[name="comment"]');

      if (phoneInput && !phoneInput.value.trim()) {
        phoneInput.focus();
        return;
      }

      const utmData = typeof window.getSavedUtm === 'function' ? window.getSavedUtm() : {};

      const payload = {
        name: nameInput?.value?.trim() || '',
        phone: phoneInput?.value?.trim() || '',
        email: emailInput?.value?.trim() || '',
        city: cityInput?.value?.trim() || '',
        volume: volumeInput?.value?.trim() || '',
        comment: commentInput?.value?.trim() || '',
        logistics: logisticsSummary(form, syncLogistics(form)),
        website: form.querySelector('[name="website"]')?.value || '',
        ...utmData
      };

      // Fire Meta Pixel & Google Analytics Lead Conversion Event
      if (typeof window.trackAdEvent === 'function') {
        window.trackAdEvent('Lead', {
          content_name: 'Wood Pellets Wholesale Inquiry',
          content_category: 'Biofuel B2B',
          city: payload.city,
          volume: payload.volume,
          currency: 'UAH',
          value: 75000 // Sample nominal order value for 15 tons
        });
      }

      // Close modal if open
      if (contactModal && contactModal.open) {
        contactModal.close();
      }

      // Reset inputs
      form.reset();

      // Show instant feedback toast
      const lang = localStorage.getItem('site_lang') || 'uk';
      const successMessage = lang === 'uk'
        ? "Дякуємо! Ваша заявка прийнята. Менеджер зв'яжеться з вами протягом 15 хвилин."
        : "Thank you! Your quote request has been received. Our sales manager will contact you within 15 minutes.";

      showToast(successMessage);

      // Open Telegram with pre-filled lead summary (popup to your number)
      const contacts = window.APP_CONFIG?.CONTACTS;
      const tgUrl = contacts?.telegram_url || 'https://t.me/+380664035396';
      const leadMsg = [
        '🟢 Нова B2B заявка з сайту',
        `👤 Ім'я: ${payload.name || '—'}`,
        `📞 Телефон: ${payload.phone}`,
        payload.email ? `✉️ Email: ${payload.email}` : '',
        payload.city ? `📍 Місто: ${payload.city}` : '',
        payload.volume ? `⚖️ Об'єм: ${payload.volume}` : '',
        payload.logistics ? `🚚 Логістика:\n${payload.logistics}` : '',
        payload.comment ? `💬 Коментар: ${payload.comment}` : '',
        utmData.utm_source ? `📊 UTM: ${utmData.utm_source} / ${utmData.utm_campaign || '—'}` : ''
      ].filter(Boolean).join('\n');
      const tgDeepLink = `${tgUrl}?text=${encodeURIComponent(leadMsg)}`;
      window.open(tgDeepLink, '_blank');

      // Submit to backend API (/api/lead) asynchronously
      try {
        await fetch('/api/lead', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(payload)
        });
      } catch (err) {
        // Fail silently on static previews
        console.log('[Lead Submission Note] Static environment fallback', err);
      }
    });
  });
});
